# check if a username is a string, is not None, and is longer than 5 characters

username = ""
# 1. using isInstance(username, str) checks if string
# 2. username is not None 
# 3. len(username) > 5 (length check )
checking = isinstance(username, str) and username != None and len(username) > 5
print(checking)




